def prepare_panel_window(widget):
    """Make the popup float above everything, on every Space / desktop,
    without stealing the previous app's activation. Call after the widget
    exists (create()) and before show().

    macOS: NSPanel with the non-activating mask at level 25, joins all
    Spaces. Keyboard focus still works (makeKeyAndOrderFront in show_panel).
    Windows: nothing native needed; the panel activates normally and the
    previous window is restored with restore_front_app() when pasting.
    """
    if not IS_MACOS:
        return
    try:
        import ctypes as _ct
        import objc
        from AppKit import (
            NSWindowCollectionBehaviorCanJoinAllSpaces,
            NSWindowCollectionBehaviorStationary,
            NSWindowCollectionBehaviorIgnoresCycle,
            NSWindowCollectionBehaviorFullScreenAuxiliary,
            NSWindowCollectionBehaviorTransient,
            NSWindowStyleMaskNonactivatingPanel,
        )
        widget.create()
        ptr = int(widget.winId())
        if ptr == 0:
            return
        nsview = objc.objc_object(c_void_p=_ct.c_void_p(ptr))
        nswindow = nsview.window()
        if nswindow is None:
            return
        nswindow.setLevel_(25)
        nswindow.setHidesOnDeactivate_(False)
        nswindow.setCollectionBehavior_(
            NSWindowCollectionBehaviorCanJoinAllSpaces
            | NSWindowCollectionBehaviorStationary
            | NSWindowCollectionBehaviorIgnoresCycle
            | NSWindowCollectionBehaviorFullScreenAuxiliary
            | NSWindowCollectionBehaviorTransient
        )
        try:
            nswindow.setStyleMask_(int(nswindow.styleMask()) | NSWindowStyleMaskNonactivatingPanel)
        except Exception:
            pass
    except Exception as e:
        print(f"prepare_panel_window: {e}")


def focus_panel_window(widget):
    """Give the shown panel keyboard focus.

    macOS: makeKeyAndOrderFront on the non-activating panel is enough for
    typing; we deliberately do NOT activate our own app so the previous
    app keeps its activation and receives the Cmd+V later.
    """
    if IS_MACOS:
        try:
            import ctypes as _ct
            import objc
            ptr = int(widget.winId())
            nsview = objc.objc_object(c_void_p=_ct.c_void_p(ptr))
            nswindow = nsview.window()
            if nswindow is not None:
                nswindow.makeKeyAndOrderFront_(None)
        except Exception as e:
            print(f"focus_panel_window: {e}")
    elif IS_WINDOWS:
        try:
            user32 = ctypes.windll.user32
            kernel32 = ctypes.windll.kernel32
            hwnd = int(widget.winId())
            fg = user32.GetForegroundWindow()
            cur_tid = kernel32.GetCurrentThreadId()
            fg_tid = user32.GetWindowThreadProcessId(fg, None) if fg else 0
            attached = False
            if fg_tid and fg_tid != cur_tid:
                attached = bool(user32.AttachThreadInput(fg_tid, cur_tid, True))
            try:
                user32.BringWindowToTop(hwnd)
                user32.SetForegroundWindow(hwnd)
                user32.SetFocus(hwnd)
            finally:
                if attached:
                    user32.AttachThreadInput(fg_tid, cur_tid, False)
        except Exception as e:
            print(f"focus_panel_window: {e}")
    widget.activateWindow()


