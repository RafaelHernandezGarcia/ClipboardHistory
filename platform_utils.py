def _launch_agent_path():
    return os.path.expanduser(f"~/Library/LaunchAgents/{BUNDLE_ID}.plist")


def _startup_link_windows():
    startup = os.path.join(os.environ.get("APPDATA", ""), "Microsoft", "Windows",
                           "Start Menu", "Programs", "Startup")
    return os.path.join(startup, f"{APP_NAME}.lnk")


def startup_enabled():
    if IS_MACOS:
        return os.path.exists(_launch_agent_path())
    if IS_WINDOWS:
        return os.path.exists(_startup_link_windows())
    return False


def set_startup_enabled(enabled, python_exe, main_py, icon_path=None):
    """macOS: LaunchAgent that runs `python_exe main_py` at login (and keeps
    it alive). Windows: shortcut in the Startup folder (pythonw.exe so no
    console window). Returns True on success."""
    if IS_MACOS:
        plist = _launch_agent_path()
        label = BUNDLE_ID
        try:
            import subprocess
            uid = os.getuid()
            if not enabled:
                subprocess.run(["launchctl", "bootout", f"gui/{uid}/{label}"],
                               stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                if os.path.exists(plist):
                    os.remove(plist)
                return True
            os.makedirs(os.path.dirname(plist), exist_ok=True)
            workdir = os.path.dirname(os.path.abspath(main_py))
            with open(plist, "w", encoding="utf-8") as f:
                f.write(f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>{label}</string>
  <key>ProgramArguments</key>
  <array>
    <string>{python_exe}</string>
    <string>{main_py}</string>
  </array>
  <key>WorkingDirectory</key><string>{workdir}</string>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict>
  <key>StandardErrorPath</key><string>/tmp/clipboardhistory_agent.log</string>
  <key>StandardOutPath</key><string>/tmp/clipboardhistory_agent.log</string>
</dict></plist>
""")
            # Do not bootstrap here: the running process IS the app; the agent
            # takes over at next login (or `launchctl bootstrap` from a shell).
            return True
        except Exception as e:
            print(f"set_startup_enabled: {e}")
            return False
    if IS_WINDOWS:
        link = _startup_link_windows()
        try:
            if not enabled:
                if os.path.exists(link):
                    os.remove(link)
                return True
            exe = python_exe
            if exe.lower().endswith("python.exe"):
                cand = exe[:-len("python.exe")] + "pythonw.exe"
                if os.path.exists(cand):
                    exe = cand
            from win32com.client import Dispatch  # pywin32
            shell = Dispatch("WScript.Shell")
            sc = shell.CreateShortCut(link)
            sc.Targetpath = exe
            sc.Arguments = f'"{main_py}"'
            sc.WorkingDirectory = os.path.dirname(os.path.abspath(main_py))
            sc.Description = f"{APP_NAME} - auto start"
            if icon_path and os.path.exists(icon_path):
                sc.IconLocation = icon_path
            sc.save()
            return True
        except Exception as e:
            print(f"set_startup_enabled: {e}")
            return False
    return False


def set_process_identity():
    """Cosmetics: no Dock icon on macOS, 'ClipboardHistory' (not Python) as
    the toast / taskbar identity on Windows. Call before QApplication."""
    if IS_MACOS:
        try:
            import AppKit
            AppKit.NSBundle.mainBundle().infoDictionary()["LSUIElement"] = "1"
        except Exception:
            pass
    elif IS_WINDOWS:
        try:
            ctypes.windll.shell32.SetCurrentProcessExplicitAppUserModelID("RMScience.ClipboardHistory")
        except Exception:
            pass


def pin_as_accessory_app():
    """macOS: menu-bar utility (no Dock icon, no app switcher entry)."""
    if IS_MACOS:
        try:
            import AppKit
            if AppKit.NSApp is not None:
                AppKit.NSApp.setActivationPolicy_(1)  # NSApplicationActivationPolicyAccessory
        except Exception:
            pass


