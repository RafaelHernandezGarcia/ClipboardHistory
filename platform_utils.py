def remember_front_app():
    """Opaque token for the app/window that had focus when the hotkey fired."""
    if IS_MACOS:
        try:
            from AppKit import NSWorkspace
            return NSWorkspace.sharedWorkspace().frontmostApplication()
        except Exception:
            return None
    if IS_WINDOWS:
        try:
            return int(ctypes.windll.user32.GetForegroundWindow())
        except Exception:
            return None
    return None


def front_app_name(token=None):
    """Human name of the app behind a remember_front_app() token (or the
    current frontmost app when token is None)."""
    if token is None:
        token = remember_front_app()
    if token is None:
        return ""
    if IS_MACOS:
        try:
            return str(token.localizedName() or "")
        except Exception:
            return ""
    if IS_WINDOWS:
        try:
            pid = ctypes.wintypes.DWORD()
            ctypes.windll.user32.GetWindowThreadProcessId(token, ctypes.byref(pid))
            h = ctypes.windll.kernel32.OpenProcess(0x1000, False, pid.value)  # QUERY_LIMITED_INFORMATION
            if not h:
                return ""
            buf = ctypes.create_unicode_buffer(1024)
            size = ctypes.wintypes.DWORD(1024)
            ok = ctypes.windll.kernel32.QueryFullProcessImageNameW(h, 0, buf, ctypes.byref(size))
            ctypes.windll.kernel32.CloseHandle(h)
            if ok:
                return os.path.splitext(os.path.basename(buf.value))[0]
        except Exception:
            pass
    return ""


def restore_front_app(token):
    """Give focus back to the app captured by remember_front_app()."""
    if token is None:
        return
    if IS_MACOS:
        try:
            # NSApplicationActivateIgnoringOtherApps = 1 << 1
            token.activateWithOptions_(1 << 1)
        except Exception as e:
            print(f"restore_front_app: {e}")
    elif IS_WINDOWS:
        try:
            user32 = ctypes.windll.user32
            kernel32 = ctypes.windll.kernel32
            fg = user32.GetForegroundWindow()
            cur_tid = kernel32.GetCurrentThreadId()
            fg_tid = user32.GetWindowThreadProcessId(fg, None) if fg else 0
            attached = False
            if fg_tid and fg_tid != cur_tid:
                attached = bool(user32.AttachThreadInput(fg_tid, cur_tid, True))
            try:
                user32.SetForegroundWindow(token)
            finally:
                if attached:
                    user32.AttachThreadInput(fg_tid, cur_tid, False)
        except Exception as e:
            print(f"restore_front_app: {e}")


def can_send_keystrokes():
    """macOS needs the Accessibility permission to post a Cmd+V keystroke.
    Windows needs nothing."""
    if not IS_MACOS:
        return True
    try:
        import ctypes as _ct
        import ctypes.util
        ax = _ct.CDLL(_ct.util.find_library("ApplicationServices"))
        ax.AXIsProcessTrusted.restype = _ct.c_bool
        return bool(ax.AXIsProcessTrusted())
    except Exception:
        return False


def request_keystroke_permission():
    """Show the macOS Accessibility prompt / open the settings pane."""
    if not IS_MACOS:
        return
    try:
        from ApplicationServices import AXIsProcessTrustedWithOptions, kAXTrustedCheckOptionPrompt
        AXIsProcessTrustedWithOptions({kAXTrustedCheckOptionPrompt: True})
    except Exception:
        pass
    try:
        import subprocess
        subprocess.Popen(["open",
                          "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility"],
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except Exception:
        pass


def send_paste_keystroke():
    """Type Cmd+V (macOS) / Ctrl+V (Windows) into the focused app.
    Returns False when it could not be sent (no permission)."""
    if IS_MACOS:
        if not can_send_keystrokes():
            return False
        try:
            from Quartz import (
                CGEventCreateKeyboardEvent, CGEventPost, CGEventSetFlags,
                kCGHIDEventTap, kCGEventFlagMaskCommand,
            )
            kVK_V = 9
            down = CGEventCreateKeyboardEvent(None, kVK_V, True)
            up = CGEventCreateKeyboardEvent(None, kVK_V, False)
            CGEventSetFlags(down, kCGEventFlagMaskCommand)
            CGEventSetFlags(up, kCGEventFlagMaskCommand)
            CGEventPost(kCGHIDEventTap, down)
            time.sleep(0.01)
            CGEventPost(kCGHIDEventTap, up)
            return True
        except Exception as e:
            print(f"send_paste_keystroke: {e}")
            return False
    if IS_WINDOWS:
        try:
            user32 = ctypes.windll.user32
            VK_CONTROL, VK_V, KEYEVENTF_KEYUP = 0x11, 0x56, 0x0002
            # Release modifiers the user may still be holding from the hotkey
            # (Ctrl+Shift+V) so the app sees a clean Ctrl+V.
            for vk in (0x10, 0x12, 0x5B):  # Shift, Alt, LWin
                if user32.GetAsyncKeyState(vk) & 0x8000:
                    user32.keybd_event(vk, 0, KEYEVENTF_KEYUP, 0)
            user32.keybd_event(VK_CONTROL, 0, 0, 0)
            user32.keybd_event(VK_V, 0, 0, 0)
            user32.keybd_event(VK_V, 0, KEYEVENTF_KEYUP, 0)
            user32.keybd_event(VK_CONTROL, 0, KEYEVENTF_KEYUP, 0)
            return True
        except Exception as e:
            print(f"send_paste_keystroke: {e}")
            return False
    return False


def modifiers_released():
    """True once the user let go of Cmd/Ctrl/Shift after the hotkey. Sending
    Cmd+V while Shift is still down would paste-without-formatting or nothing."""
    if IS_MACOS:
        try:
            from AppKit import NSEvent
            flags = int(NSEvent.modifierFlags())
            # shift 1<<17, control 1<<18, option 1<<19, command 1<<20
            return not (flags & ((1 << 17) | (1 << 18) | (1 << 19) | (1 << 20)))
        except Exception:
            return True
    if IS_WINDOWS:
        try:
            user32 = ctypes.windll.user32
            for vk in (0x10, 0x11, 0x12, 0x5B, 0x5C):
                if user32.GetAsyncKeyState(vk) & 0x8000:
                    return False
            return True
        except Exception:
            return True
    return True


