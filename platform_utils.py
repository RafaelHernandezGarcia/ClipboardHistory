_click_monitor = None  # retained for the process lifetime


def install_outside_click_monitor(widget, callback):
    """Call callback() when the mouse is pressed anywhere outside `widget`
    while it is visible. Qt's WindowDeactivate covers most cases; on macOS a
    non-activating panel does not always get one, so a global NSEvent
    monitor for mouse-down (no permission needed for mouse events) is
    added as a safety net. No-op elsewhere."""
    global _click_monitor
    if not IS_MACOS:
        return
    try:
        from AppKit import NSEvent, NSEventMaskLeftMouseDown, NSEventMaskRightMouseDown

        def _handler(event):
            try:
                if widget.isVisible():
                    callback()
            except Exception as e:
                print(f"outside-click: {e}")

        _click_monitor = NSEvent.addGlobalMonitorForEventsMatchingMask_handler_(
            NSEventMaskLeftMouseDown | NSEventMaskRightMouseDown, _handler)
    except Exception as e:
        print(f"install_outside_click_monitor: {e}")
