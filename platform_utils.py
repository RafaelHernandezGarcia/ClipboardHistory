"""Every OS-specific bit of ClipboardHistory lives here (IS_MACOS / IS_WINDOWS).

Do not add sys.platform checks elsewhere: the rest of the app is plain Qt.
Same rule as ScreenCapture, same reason - one codebase for both laptops.

What this module covers:
    data_dir()                  where history + images are stored
    clipboard_sequence()        cheap "did the clipboard change" counter
    clipboard_is_private()      password-manager / transient flags -> skip
    write_text/image/files()    put an item back on the clipboard (native
                                on macOS so every app can paste it)
    remember_front_app()        who had focus before the panel opened
    restore_front_app(token)    give it focus back
    send_paste_keystroke()      simulate Cmd+V / Ctrl+V
    can_send_keystrokes()       macOS Accessibility permission check
    prepare_panel_window()      floating, non-activating, all-Spaces panel
    startup_enabled/set_...()   launch at login (LaunchAgent / Startup lnk)
"""
import os
import sys
import time

IS_MACOS = sys.platform == "darwin"
IS_WINDOWS = sys.platform == "win32"

APP_NAME = "ClipboardHistory"
BUNDLE_ID = "com.clipboardhistory.app"
SYSTEM_FONT = ".AppleSystemUIFont" if IS_MACOS else ("Segoe UI" if IS_WINDOWS else "Sans Serif")
PASTE_MODIFIER_LABEL = "Cmd" if IS_MACOS else "Ctrl"

if IS_WINDOWS:
    import ctypes
    import ctypes.wintypes


# ---------------------------------------------------------------------------
# Folders
# ---------------------------------------------------------------------------

def data_dir():
    """Per-user folder for history.json and the images/ subfolder.
    Env CLIPBOARDHISTORY_DATA_DIR overrides it (tests, side-by-side copies)."""
    override = os.environ.get("CLIPBOARDHISTORY_DATA_DIR")
    if override:
        os.makedirs(os.path.join(override, "images"), exist_ok=True)
        return override
    if IS_MACOS:
        base = os.path.expanduser("~/Library/Application Support")
    elif IS_WINDOWS:
        base = os.environ.get("LOCALAPPDATA") or os.path.expanduser("~")
    else:
        base = os.environ.get("XDG_DATA_HOME") or os.path.expanduser("~/.local/share")
    path = os.path.join(base, APP_NAME)
    os.makedirs(os.path.join(path, "images"), exist_ok=True)
    return path


def open_folder(path):
    try:
        import subprocess
        if IS_MACOS:
            subprocess.Popen(["open", path])
        elif IS_WINDOWS:
            os.startfile(path)  # type: ignore[attr-defined]
        else:
            subprocess.Popen(["xdg-open", path])
    except Exception as e:
        print(f"open_folder: {e}")


# ---------------------------------------------------------------------------
# Clipboard change detection + privacy flags
# ---------------------------------------------------------------------------

def clipboard_sequence():
    """Monotonic counter that changes whenever the clipboard content changes.

    macOS: NSPasteboard changeCount. Windows: GetClipboardSequenceNumber.
    Elsewhere: None (the watcher falls back to Qt's dataChanged signal).
    """
    if IS_MACOS:
        try:
            from AppKit import NSPasteboard
            return int(NSPasteboard.generalPasteboard().changeCount())
        except Exception:
            return None
    if IS_WINDOWS:
        try:
            return int(ctypes.windll.user32.GetClipboardSequenceNumber())
        except Exception:
            return None
    return None


def clipboard_is_private():
    """True when the current clipboard content asks not to be recorded.

    Password managers (1Password, Bitwarden...) flag their copies:
    macOS  - org.nspasteboard.ConcealedType / TransientType
    Windows - the ExcludeClipboardContentFromMonitorProcessing format
    """
    if IS_MACOS:
        try:
            from AppKit import NSPasteboard
            types = set(NSPasteboard.generalPasteboard().types() or [])
            return bool(types & {"org.nspasteboard.ConcealedType",
                                 "org.nspasteboard.TransientType",
                                 "org.nspasteboard.AutoGeneratedType"})
        except Exception:
            return False
    if IS_WINDOWS:
        try:
            user32 = ctypes.windll.user32
            fmt = user32.RegisterClipboardFormatW("ExcludeClipboardContentFromMonitorProcessing")
            return bool(fmt and user32.IsClipboardFormatAvailable(fmt))
        except Exception:
            return False
    return False


# ---------------------------------------------------------------------------
# Writing items back to the clipboard
# ---------------------------------------------------------------------------

def write_text(text):
    """Plain text -> clipboard."""
    if IS_MACOS:
        try:
            from AppKit import NSPasteboard, NSPasteboardTypeString
            pb = NSPasteboard.generalPasteboard()
            pb.clearContents()
            pb.setString_forType_(text, NSPasteboardTypeString)
            return True
        except Exception as e:
            print(f"write_text (native): {e}")
    from PyQt6.QtWidgets import QApplication
    QApplication.clipboard().setText(text)
    return True


def write_image(png_bytes):
    """PNG bytes -> clipboard. macOS publishes TIFF + PNG through NSImage so
    Mail, Pages, Slack, Photoshop... all accept the paste."""
    if IS_MACOS:
        try:
            from AppKit import NSPasteboard, NSImage
            from Foundation import NSData
            data = NSData.dataWithBytes_length_(png_bytes, len(png_bytes))
            img = NSImage.alloc().initWithData_(data)
            pb = NSPasteboard.generalPasteboard()
            pb.clearContents()
            if img is not None and pb.writeObjects_([img]):
                return True
        except Exception as e:
            print(f"write_image (native): {e}")
    from PyQt6.QtWidgets import QApplication
    from PyQt6.QtGui import QImage
    img = QImage.fromData(png_bytes, "PNG")
    QApplication.clipboard().setImage(img)
    return True


def write_files(paths):
    """List of file paths -> clipboard (Finder / Explorer can paste them)."""
    paths = [p for p in paths if os.path.exists(p)]
    if not paths:
        return False
    if IS_MACOS:
        try:
            from AppKit import NSPasteboard
            from Foundation import NSURL
            pb = NSPasteboard.generalPasteboard()
            pb.clearContents()
            urls = [NSURL.fileURLWithPath_(p) for p in paths]
            if pb.writeObjects_(urls):
                return True
        except Exception as e:
            print(f"write_files (native): {e}")
    from PyQt6.QtWidgets import QApplication
    from PyQt6.QtCore import QMimeData, QUrl
    mime = QMimeData()
    mime.setUrls([QUrl.fromLocalFile(p) for p in paths])
    mime.setText("\n".join(paths))
    QApplication.clipboard().setMimeData(mime)
    return True


